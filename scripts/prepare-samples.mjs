import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createImageUploader } from 'img-upload-kit/server';
import { createLocalFsStorageAdapter } from 'img-upload-kit/storage';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const assetsDir = path.join(rootDir, 'assets', 'landscapes');
const publicSamplesDir = path.join(rootDir, 'public', 'samples');
const outTsPath = path.join(rootDir, 'src', 'data', 'landscapeSamples.ts');

const SPECS = [
  {
    file: 'misty-nordic-fjord.jpg',
    slug: 'glacial-mountain-peaks',
    label: 'Glacial peaks',
    preset: 'cover',
    altText: 'Snow-capped alpine mountain range overlooking evergreen valley',
  },
  {
    file: 'golden-desert-dunes.jpg',
    slug: 'sahara-golden-dunes',
    label: 'Sahara dunes',
    preset: 'hero',
    altText: 'Warm golden desert sand dunes under twilight sky',
  },
  {
    file: 'coastal-sunset-cliffs.jpg',
    slug: 'pacific-sunset-shore',
    label: 'Pacific sunset',
    preset: 'card',
    altText: 'Golden sunset reflection across turquoise ocean waves and sandy shore',
  },
  {
    file: 'alpine-emerald-lake.jpg',
    slug: 'yosemite-dawn-valley',
    label: 'Yosemite dawn',
    preset: 'cover',
    altText: 'Yosemite valley granite cliffs and misty pines reflected in dawn river',
  },
];

async function main() {
  await fs.rm(publicSamplesDir, { recursive: true, force: true });
  await fs.mkdir(publicSamplesDir, { recursive: true });

  const storage = createLocalFsStorageAdapter({
    rootDir: publicSamplesDir,
    baseUrl: '/samples',
  });

  const uploader = createImageUploader({
    storage,
    defaultBucket: 'landscapes',
    includeBlurHash: true,
    concurrency: 2,
  });

  const entries = [];
  for (const spec of SPECS) {
    const filePath = path.join(assetsDir, spec.file);
    const buffer = await fs.readFile(filePath);
    const data = await uploader.uploadImage(
      { buffer, name: spec.file, type: 'image/jpeg' },
      {
        preset: spec.preset,
        folder: 'preset-' + spec.preset,
        customFilename: spec.slug,
        altText: spec.altText,
        includeBlurHash: true,
      },
    );
    const savings = data.originalSize
      ? Math.max(0, Math.round((1 - data.size / data.originalSize) * 100))
      : 0;
    console.log(
      `[img-upload-kit] ${spec.label}: ${(buffer.byteLength / 1024).toFixed(1)} KB -> ${(data.size / 1024).toFixed(1)} KB ${data.format.toUpperCase()} (-${savings}%) | color=${data.blurColor} | hash=${data.blurHash}`,
    );
    entries.push({ label: spec.label, preset: spec.preset, data });
  }

  const tsContent = `// Auto-generated by scripts/prepare-samples.mjs using img-upload-kit/server (Sharp + LQIP + BlurHash + 4-edge color)
import type { StandardPresetName, UploadedImageData } from 'img-upload-kit';

export interface StudioImageEntry {
  id: string;
  label: string;
  preset: StandardPresetName;
  isUserUpload?: boolean;
  data: UploadedImageData;
}

export const LANDSCAPE_SAMPLES: StudioImageEntry[] = ${JSON.stringify(
    entries.map((e) => ({
      id: e.data.url,
      label: e.label,
      preset: e.preset,
      isUserUpload: false,
      data: e.data,
    })),
    null,
    2,
  )};

export const DEFAULT_LANDSCAPE_ENTRY: StudioImageEntry = LANDSCAPE_SAMPLES[0];
`;

  await fs.writeFile(outTsPath, tsContent, 'utf8');
  console.log(`Wrote ${entries.length} real landscape samples to ${outTsPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
